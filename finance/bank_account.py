"""Module containing the BankAccount class."""

import math
import re
from dataclasses import dataclass, InitVar


@dataclass
class BankAccount:
    """A bank account with a protected balance and PIN code.

    Public fields (generated by dataclass): owner, account_number, currency.
    Private data: __balance and __pin (accessible only through properties).
    """

    owner: str
    account_number: str
    initial_balance: InitVar[float] = 0.0
    pin: InitVar[str] = "4821"
    currency: str = "UAH"

    # Account number pattern: "UA" + 8 digits
    _ACCOUNT_PATTERN = re.compile(r"^UA\d{8}$")

    def __post_init__(self, initial_balance: float, pin: str) -> None:
        """Validates the input data and creates the private attributes."""
        if not isinstance(self.owner, str) or not self.owner.strip():
            raise ValueError("Owner name cannot be empty.")
        self.owner = self.owner.strip()

        if not isinstance(self.account_number, str) or not self._ACCOUNT_PATTERN.match(self.account_number):
            raise ValueError("Account number must be 'UA' followed by 8 digits, e.g. UA12345678.")

        # Private (protected) data
        self.__balance = 0.0
        self.__pin = ""

        # Assign through the properties so that validation is applied
        self.balance = initial_balance
        self.pin = pin

    # ---------- Properties ----------

    @property
    def balance(self) -> float:
        """Current account balance."""
        return self.__balance

    @balance.setter
    def balance(self, value: float) -> None:
        """Sets the balance; negative and invalid values are rejected."""
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise ValueError("Balance must be a number.")
        if not math.isfinite(value):
            raise ValueError("Balance must be a finite number.")
        if value < 0:
            raise ValueError("Balance cannot be negative.")
        self.__balance = round(float(value), 2)

    @property
    def pin(self) -> str:
        """The PIN code cannot be read from outside the class."""
        raise AttributeError("The PIN code is write-only.")

    @pin.setter
    def pin(self, value: str) -> None:
        """Sets the PIN code; weak codes are rejected."""
        if not isinstance(value, str) or not value.isdigit() or len(value) != 4:
            raise ValueError("PIN code must consist of exactly 4 digits.")
        if len(set(value)) == 1 or value in ("1234", "4321", "0123"):
            raise ValueError("PIN code is too simple.")
        self.__pin = value

    # ---------- Helper methods ----------

    @staticmethod
    def _validate_amount(amount: float) -> float:
        """Validates an operation amount and returns it rounded to cents."""
        if isinstance(amount, bool) or not isinstance(amount, (int, float)):
            raise ValueError("Amount must be a number.")
        if not math.isfinite(amount) or amount <= 0:
            raise ValueError("Amount must be positive.")
        return round(float(amount), 2)

    # ---------- Regular methods ----------

    def check_pin(self, entered_pin: str) -> bool:
        """Returns True if the entered PIN matches the stored one."""
        return entered_pin == self.__pin

    def deposit(self, amount: float) -> None:
        """Adds the given amount to the account."""
        amount = self._validate_amount(amount)
        self.__balance = round(self.__balance + amount, 2)

    def withdraw(self, amount: float, entered_pin: str) -> None:
        """Withdraws funds after checking the PIN and the available balance."""
        if not self.check_pin(entered_pin):
            raise ValueError("Incorrect PIN code.")
        amount = self._validate_amount(amount)
        if amount > self.__balance:
            raise ValueError("Insufficient funds.")
        self.__balance = round(self.__balance - amount, 2)

    def transfer_to(self, other: "BankAccount", amount: float, entered_pin: str) -> None:
        """Transfers funds to another account with the same currency."""
        if not isinstance(other, BankAccount):
            raise ValueError("The recipient must be a bank account.")
        if other is self:
            raise ValueError("Cannot transfer funds to the same account.")
        if other.currency != self.currency:
            raise ValueError("Account currencies do not match.")
        # Withdraw first (with all checks), then deposit
        self.withdraw(amount, entered_pin)
        other.deposit(amount)

    def change_pin(self, old_pin: str, new_pin: str) -> None:
        """Changes the PIN code after verifying the old one."""
        if not self.check_pin(old_pin):
            raise ValueError("Incorrect old PIN code.")
        self.pin = new_pin

    def print_info(self) -> None:
        """Prints account information (the PIN is never shown)."""
        print(f"Owner:          {self.owner}")
        print(f"Account number: {self.account_number}")
        print(f"Balance:        {self.balance:.2f} {self.currency}")
